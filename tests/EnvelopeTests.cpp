void runEnvelopeTests()
{
    DrumAudioProcessor p;auto& library=p.getLibrary();auto state=library.snapshot();const auto kit=state.activeKit,group=drum::activeKit(state)->groups.front().id;
    const auto id=library.addInstrument(kit,group).id;
    // Generated by the earlier preview test; decoded through the normal loader.
    auto file=juce::File::getCurrentWorkingDirectory().getChildFile("playback-test-data/Preview percussion.wav");
    p.getSampleEngine().requestLoad(kit,id,file);check(p.getSampleEngine().waitForLoading(10000),"Envelope sample load timed out");
    check(p.getSampleEngine().statusFor(id).ready,"Envelope fixture unavailable");p.getSampleEngine().prepare(48000);
    DrumAudioProcessorEditor editor(p);editor.setSize(1280,900);click(editor,"open-sound-editor");click(editor,"edit-tab-1");settle(editor);
    auto current=[&]{auto s=library.snapshot();return drum::findInstrument(*drum::activeKit(s),id)->controls;};
    auto& amp=control<EnvelopeEditor>(editor,"envelope-amp");auto& pitch=control<EnvelopeEditor>(editor,"envelope-pitch");auto& filter=control<EnvelopeEditor>(editor,"envelope-filter");
    check(amp.isVisible() && pitch.isVisible() && !filter.isVisible(),"Envelope graphs shown on wrong page");
    check(control<juce::TextButton>(editor,"envelope-amp-activate").isVisible(),"Inactive amplitude has no Classic control");
    auto& wave=control<juce::Component>(editor,"sample-waveform");const auto waveBounds=wave.getBounds();
    drag(control<juce::Component>(editor,"envelope-amp-attack"),{40,0});check(current().sound.mode==0,"Editing inactive envelope silently enabled Classic");
    click(editor,"envelope-amp-activate");settle(editor);check(current().sound.mode==2,"Use Classic failed");const auto beforeWave=pixels(wave);
    auto before=current().sound;drag(control<juce::Component>(editor,"envelope-amp-decay"),{30,25});
    auto after=current().sound;check(after.ampDecay>before.ampDecay && after.ampSustain<before.ampSustain,"Decay drag did not edit time and level together");
    before=after;drag(control<juce::Component>(editor,"envelope-amp-sustain"),{80,10});after=current().sound;
    check(after.ampSustain<before.ampSustain && after.ampDecay==before.ampDecay,"Sustain drag changed time");
    drag(control<juce::Component>(editor,"envelope-amp-release"),{40,0});check(current().sound.ampRelease>before.ampRelease,"Release drag failed");
    settle(editor);check(pixels(wave)!=beforeWave,"Envelope drag did not update Edited waveform");
    check(std::abs(control<juce::Slider>(editor,"edit-ampSustain").getValue()-current().sound.ampSustain*100)<0.0001,"Envelope drag did not update slider");
    auto oldPoint=control<juce::Component>(editor,"envelope-amp-attack").getBounds();
    control<juce::Slider>(editor,"edit-ampAttack").setValue(25,juce::sendNotificationSync);
    check(oldPoint!=control<juce::Component>(editor,"envelope-amp-attack").getBounds(),"Slider did not update envelope point");
    // The attack segment itself is draggable, not just its grip.
    const auto peak=control<juce::Component>(editor,"envelope-amp-attack").getBounds().getCentre().toFloat();
    const auto mid=(peak+juce::Point<float>{35,(float)amp.getHeight()-40})*0.5f;
    amp.mouseDown(event(amp,mid,mid));amp.mouseDrag(event(amp,mid+juce::Point<float>{20,0},mid));amp.mouseUp(event(amp,mid+juce::Point<float>{20,0},mid));
    check(current().sound.ampAttack>25,"Envelope line drag failed");
    const auto saved=library.toXml()->toString();click(editor,"envelope-amp-zoom-in");click(editor,"envelope-amp-zoom-out");click(editor,"envelope-amp-fit");
    check(library.toXml()->toString()==saved,"Envelope view controls changed sound");
    drag(control<juce::Component>(editor,"envelope-amp-attack"),{100000,0});check(current().sound.ampAttack==20000,"Attack drag exceeded maximum");
    drag(control<juce::Component>(editor,"envelope-amp-release"),{100000,0});check(current().sound.ampRelease==30000,"Release drag exceeded maximum");
    drag(control<juce::Component>(editor,"envelope-amp-sustain"),{0,100000});check(current().sound.ampSustain==0,"Sustain drag exceeded minimum");
    click(editor,"reset-edit-page");check(current().sound.ampAttack==0 && current().sound.ampSustain==1,"Page reset did not restore envelope");
    // Negative modulation points move down from zero; numeric sustain remains positive.
    control<juce::Slider>(editor,"edit-pitchAmount").setValue(-12,juce::sendNotificationSync);
    drag(control<juce::Component>(editor,"envelope-pitch-sustain"),{0,30});check(current().sound.pitchSustain>0.3,"Negative pitch envelope drag inverted incorrectly");
    auto& pitchA=control<juce::Component>(editor,"envelope-pitch-attack");
    check(pitchA.keyPressed(juce::KeyPress(juce::KeyPress::rightKey)) && current().sound.pitchAttack==1,"Keyboard envelope edit failed");
    control<juce::Slider>(editor,"edit-ampAttack").setValue(35,juce::sendNotificationSync);
    control<juce::Slider>(editor,"edit-ampDecay").setValue(130,juce::sendNotificationSync);
    control<juce::Slider>(editor,"edit-ampSustain").setValue(40,juce::sendNotificationSync);settle(editor);
    capture(editor,"drum-envelopes.png");editor.setSize(800,600);
    check(amp.getBottom()<=control<juce::Viewport>(editor,"sound-controls").getHeight(),"Compact envelope values clipped below viewport");
    capture(editor,"drum-envelopes-compact.png");editor.setSize(1280,900);
    click(editor,"edit-tab-2");check(filter.isVisible() && !amp.isVisible() && wave.getBounds()==waveBounds,"Filter graph moved waveform");
    click(editor,"envelope-filter-activate");control<juce::Slider>(editor,"edit-filterAmount").setValue(-3,juce::sendNotificationSync);
    control<juce::Slider>(editor,"edit-cutoff").setValue(6000,juce::sendNotificationSync);
    drag(control<juce::Component>(editor,"envelope-filter-decay"),{60,25});check(current().sound.filterDecay>100 && current().sound.filterSustain>0.2,"Filter graph did not save edits");settle(editor);capture(editor,"drum-filter-envelope.png");
    // Mapped envelope stages show current host macro values and cannot overwrite a base setting.
    click(editor,"edit-tab-1");auto c=current();c.macros[0]={7,100,900};check(library.setControls(kit,id,c).ok,"Envelope mapping failed");
    state=library.snapshot();auto& soundEditor=control<SoundEditor>(editor,"sound-editor");soundEditor.select(kit,drum::findInstrument(*drum::activeKit(state),id));
    auto& ampA=control<juce::Component>(editor,"envelope-amp-attack");check(!ampA.isEnabled(),"Macro-mapped handle is editable");
    const auto baseAttack=current().sound.ampAttack;auto macroImage=pixels(amp);p.macro(0).setValueNotifyingHost(0.9f);settle(editor);
    check(pixels(amp)!=macroImage,"Host macro did not redraw envelope");drag(ampA,{30,0});drag(control<juce::Component>(editor,"envelope-amp-sustain"),{0,10});
    check(current().sound.ampAttack==baseAttack,"Envelope edit overwrote mapped base attack");
    c=current();c.macros[0]={};check(library.setControls(kit,id,c).ok,"Envelope mapping removal failed");state=library.snapshot();soundEditor.select(kit,drum::findInstrument(*drum::activeKit(state),id));check(ampA.isEnabled(),"Removed mapping kept handle disabled");
    // Switching instruments during a gesture must not apply its pending drag to the new selection.
    auto down=ampA.getLocalBounds().getCentre().toFloat();ampA.mouseDown(event(ampA,down,down));const auto original=current();
    const auto second=library.addInstrument(kit,group).id;state=library.snapshot();soundEditor.select(kit,drum::findInstrument(*drum::activeKit(state),second));
    ampA.mouseDrag(event(ampA,down+juce::Point<float>{70,0},down));ampA.mouseUp(event(ampA,down,down));
    state=library.snapshot();check(drum::findInstrument(*drum::activeKit(state),second)->controls.sound==drum::SoundParameters{} && current()==original,"Gesture crossed instrument selection");
    juce::MemoryBlock memory;p.getStateInformation(memory);DrumAudioProcessor recalled;recalled.setStateInformation(memory.getData(),(int)memory.getSize());state=recalled.getLibrary().snapshot();
    check(drum::findInstrument(*drum::activeKit(state),id)->controls==original,"Envelope graph edits not recalled");
    std::cout<<"Draggable ADSR graphs, waveform updates, signed modulation, macros, bounds and recall passed\n";
}
